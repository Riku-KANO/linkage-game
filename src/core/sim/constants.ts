/** 地形の既定の摩擦係数(TerrainSpec.friction の既定値) */
export const DEFAULT_FRICTION = 0.9;

/**
 * 動力学の内部調整値(契約の SimParams に出さないもの)。
 * 数値はヤンセン型・チェビシェフ型・不格好な四節の 3 種で安定するように決めた。
 */
export const SIM_TUNING = {
  /**
   * 接線方向の粘性係数(N·s/m、接触点ごと)。クーロン摩擦の固着側を「速度に比例する力」で近似する。
   * 陰的に解くので大きくても発散しない。固着中の滑り速度は 力 / この値(100N で 5mm/s)
   */
  frictionDamping: 20000,
  /** 負荷トルクの平滑化の時定数(s)。接触のばたつきでモーターが震えないように */
  loadFilterTime: 0.03,
  /** モーターの応答の時定数(s)。回転数は指令値へこの時定数で近づく(起動も滑らかになる) */
  motorResponseTime: 0.08,
  /**
   * 脚の点の最大速度(m/s)。死点付近で dp/dθ が発散しても脚が暴れないよう、θ̇ をこの範囲に抑える
   * (ヤンセン型 120rpm の振り脚でも 4m/s 程度なので通常は効かない)
   */
  maxPointSpeed: 6,
  /** 停動とみなす速度係数(1 − τ/τ_stall がこれ以下) */
  stallFactor: 0.02,
  /** 接触モード(固着・滑り・離れ)の反復回数の上限 */
  contactIterations: 4,
  /** 初期配置で最も低い接触点を地形から浮かせる量(m) */
  dropClearance: 0.001,
} as const;
